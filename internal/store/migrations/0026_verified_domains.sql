-- Domains a workspace has proved it controls (security Tier 1). Checks
-- deeper than a passive one run only against these and their subdomains.
-- The proof is re-checked daily; a domain whose proof has been missing for a
-- week lapses, so a domain that changes hands stops being scannable.
CREATE TABLE IF NOT EXISTS verified_domains (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	domain TEXT NOT NULL,
	token TEXT NOT NULL,
	status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'lapsed')),
	method TEXT NOT NULL DEFAULT '' CHECK (method IN ('', 'dns', 'http')),
	verified_at TIMESTAMPTZ,
	last_seen_at TIMESTAMPTZ,
	last_checked_at TIMESTAMPTZ,
	last_error TEXT NOT NULL DEFAULT '',
	next_check_at TIMESTAMPTZ NOT NULL DEFAULT NOW() + INTERVAL '1 hour',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_verified_domains_domain ON verified_domains (workspace_id, domain);
CREATE INDEX IF NOT EXISTS idx_verified_domains_due ON verified_domains (next_check_at);

GRANT SELECT, INSERT, UPDATE, DELETE ON verified_domains TO qnetward_tenant;

ALTER TABLE verified_domains ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON verified_domains;
CREATE POLICY workspace_isolation ON verified_domains
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
