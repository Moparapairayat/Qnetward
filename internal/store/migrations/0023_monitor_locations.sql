-- A monitor can run from several places at once: Qnetward's servers ("cloud",
-- agent_id NULL) and any of the workspace's probe agents. Each place keeps its
-- own latest result; the monitor's status is worked out from all of them.
-- This replaces monitors.agent_id, which allowed one place only.
CREATE TABLE IF NOT EXISTS monitor_locations (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	monitor_id BIGINT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	agent_id BIGINT REFERENCES probe_agents(id) ON DELETE CASCADE,
	status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'up', 'down')),
	last_checked_at TIMESTAMPTZ,
	last_rtt_ms DOUBLE PRECISION,
	last_error TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_monitor_locations_place ON monitor_locations (monitor_id, COALESCE(agent_id, 0));
CREATE INDEX IF NOT EXISTS idx_monitor_locations_agent ON monitor_locations (agent_id) WHERE agent_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_monitor_locations_workspace ON monitor_locations (workspace_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON monitor_locations TO qnetward_tenant;

ALTER TABLE monitor_locations ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON monitor_locations;
CREATE POLICY workspace_isolation ON monitor_locations
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

-- cloud mirrors "has a cloud location", so the scheduler's claim stays one
-- indexed lookup.
ALTER TABLE monitors ADD COLUMN IF NOT EXISTS cloud BOOLEAN NOT NULL DEFAULT TRUE;
UPDATE monitors SET cloud = FALSE WHERE agent_id IS NOT NULL;

INSERT INTO monitor_locations (monitor_id, workspace_id, agent_id, status, last_checked_at, last_rtt_ms, last_error)
SELECT id, workspace_id, agent_id, status, last_checked_at, last_rtt_ms, last_error FROM monitors
ON CONFLICT DO NOTHING;

DROP INDEX IF EXISTS idx_monitors_due;
DROP INDEX IF EXISTS idx_monitors_agent;
ALTER TABLE monitors DROP COLUMN IF EXISTS agent_id;
CREATE INDEX IF NOT EXISTS idx_monitors_due ON monitors (next_run_at) WHERE enabled AND cloud;
