-- Network devices: routers, switches, and firewalls an agent polls over SNMP.
-- Credentials (community or SNMPv3 keys) are sealed with the server's
-- encryption key and only ever sent to the agent that polls the device.
CREATE TABLE IF NOT EXISTS network_devices (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
	-- The agent that polls it; a device without one waits for an agent.
	agent_id BIGINT REFERENCES probe_agents(id) ON DELETE SET NULL,
	name TEXT NOT NULL,
	address TEXT NOT NULL,
	port INT NOT NULL DEFAULT 161 CHECK (port BETWEEN 1 AND 65535),
	version TEXT NOT NULL CHECK (version IN ('2c', '3')),
	credentials_enc TEXT NOT NULL DEFAULT '',
	interval_seconds INT NOT NULL DEFAULT 60 CHECK (interval_seconds BETWEEN 30 AND 3600),
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	status TEXT NOT NULL DEFAULT 'unknown' CHECK (status IN ('unknown', 'up', 'down')),
	last_polled_at TIMESTAMPTZ,
	last_error TEXT NOT NULL DEFAULT '',
	sys JSONB,
	interfaces JSONB,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_network_devices_workspace ON network_devices (workspace_id, name);
CREATE INDEX IF NOT EXISTS idx_network_devices_agent ON network_devices (agent_id) WHERE agent_id IS NOT NULL;

-- One row per poll: totals across interfaces.
CREATE TABLE IF NOT EXISTS device_metrics (
	device_id BIGINT NOT NULL REFERENCES network_devices(id) ON DELETE CASCADE,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	at TIMESTAMPTZ NOT NULL,
	reachable BOOLEAN NOT NULL,
	rtt_ms REAL NOT NULL DEFAULT 0,
	in_bps DOUBLE PRECISION NOT NULL DEFAULT 0,
	out_bps DOUBLE PRECISION NOT NULL DEFAULT 0,
	errors_ps DOUBLE PRECISION NOT NULL DEFAULT 0,
	if_up INT NOT NULL DEFAULT 0,
	if_down INT NOT NULL DEFAULT 0,
	PRIMARY KEY (device_id, at)
);
CREATE INDEX IF NOT EXISTS idx_device_metrics_at ON device_metrics (at);

-- One row per interface per poll, for interface charts.
CREATE TABLE IF NOT EXISTS device_if_metrics (
	device_id BIGINT NOT NULL REFERENCES network_devices(id) ON DELETE CASCADE,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	if_index INT NOT NULL,
	at TIMESTAMPTZ NOT NULL,
	in_bps DOUBLE PRECISION NOT NULL DEFAULT 0,
	out_bps DOUBLE PRECISION NOT NULL DEFAULT 0,
	errors_ps DOUBLE PRECISION NOT NULL DEFAULT 0,
	discards_ps DOUBLE PRECISION NOT NULL DEFAULT 0,
	PRIMARY KEY (device_id, if_index, at)
);
CREATE INDEX IF NOT EXISTS idx_device_if_metrics_at ON device_if_metrics (at);

