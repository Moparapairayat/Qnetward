-- Probe agents: small programs a workspace runs on its own machines, so checks
-- can start inside private networks and from more places. An agent enrolls
-- once with a short-lived token and then authenticates with its own secret.
-- Only SHA-256 hashes of either are stored.
CREATE TABLE IF NOT EXISTS probe_agents (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
	name TEXT NOT NULL,
	-- Set until the agent enrolls; cleared when it does.
	enroll_token_hash TEXT UNIQUE,
	enroll_expires_at TIMESTAMPTZ,
	secret_hash TEXT UNIQUE,
	enrolled_at TIMESTAMPTZ,
	last_seen_at TIMESTAMPTZ,
	version TEXT NOT NULL DEFAULT '',
	hostname TEXT NOT NULL DEFAULT '',
	platform TEXT NOT NULL DEFAULT '',
	remote_ip TEXT NOT NULL DEFAULT '',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_probe_agents_workspace ON probe_agents (workspace_id, created_at);

GRANT SELECT, INSERT, UPDATE, DELETE ON probe_agents TO qnetward_tenant;

ALTER TABLE probe_agents ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON probe_agents;
CREATE POLICY workspace_isolation ON probe_agents
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
