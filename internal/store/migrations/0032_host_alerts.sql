-- Host alert rules: tell someone when a host's CPU, memory, disk, or swap stays
-- at or above a threshold for a number of minutes. A rule covers one host, or
-- every host when agent_id is NULL. A state row exists while a rule is firing
-- for a host, so each breach alerts once and once more when it clears.
CREATE TABLE IF NOT EXISTS host_alert_rules (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
	agent_id BIGINT REFERENCES probe_agents(id) ON DELETE CASCADE,
	metric TEXT NOT NULL CHECK (metric IN ('cpu', 'memory', 'disk', 'swap')),
	threshold REAL NOT NULL CHECK (threshold > 0 AND threshold <= 100),
	minutes INT NOT NULL CHECK (minutes BETWEEN 1 AND 60),
	notify_email TEXT NOT NULL DEFAULT '',
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_host_alert_rules_workspace ON host_alert_rules (workspace_id, id);

CREATE TABLE IF NOT EXISTS host_alert_states (
	rule_id BIGINT NOT NULL REFERENCES host_alert_rules(id) ON DELETE CASCADE,
	agent_id BIGINT NOT NULL REFERENCES probe_agents(id) ON DELETE CASCADE,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	firing_since TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	value REAL NOT NULL DEFAULT 0,
	PRIMARY KEY (rule_id, agent_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON host_alert_rules TO qnetward_tenant;
GRANT SELECT, INSERT, UPDATE, DELETE ON host_alert_states TO qnetward_tenant;

ALTER TABLE host_alert_rules ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON host_alert_rules;
CREATE POLICY workspace_isolation ON host_alert_rules
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

ALTER TABLE host_alert_states ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON host_alert_states;
CREATE POLICY workspace_isolation ON host_alert_states
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

-- Channels that hear about agents also hear about their hosts.
UPDATE notification_channels
SET events = array_append(events, 'hosts')
WHERE 'agents' = ANY(events) AND NOT ('hosts' = ANY(events));
