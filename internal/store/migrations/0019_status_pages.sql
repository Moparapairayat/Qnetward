-- Public status pages. A page shows chosen monitors under display names the
-- workspace picks, so a visitor never sees the hostnames or addresses behind
-- them. The slug is global: it is the page's address at /status/<slug>.
CREATE TABLE IF NOT EXISTS status_pages (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$'),
	title TEXT NOT NULL,
	description TEXT NOT NULL DEFAULT '',
	published BOOLEAN NOT NULL DEFAULT FALSE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_status_pages_workspace ON status_pages (workspace_id, created_at);

CREATE TABLE IF NOT EXISTS status_page_monitors (
	page_id BIGINT NOT NULL REFERENCES status_pages(id) ON DELETE CASCADE,
	monitor_id BIGINT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	label TEXT NOT NULL DEFAULT '',
	position INTEGER NOT NULL DEFAULT 0,
	PRIMARY KEY (page_id, monitor_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON status_pages, status_page_monitors TO qnetward_tenant;

ALTER TABLE status_pages ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON status_pages;
CREATE POLICY workspace_isolation ON status_pages
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

ALTER TABLE status_page_monitors ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON status_page_monitors;
CREATE POLICY workspace_isolation ON status_page_monitors
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
