-- Workspace API keys for scripts, CI, and Terraform. Only a SHA-256 hash of
-- each token is stored; the token itself is shown once, at creation.
CREATE TABLE IF NOT EXISTS api_keys (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
	name TEXT NOT NULL,
	-- The first characters of the token, so people can tell keys apart.
	prefix TEXT NOT NULL,
	token_hash TEXT NOT NULL UNIQUE,
	scopes TEXT[] NOT NULL,
	expires_at TIMESTAMPTZ,
	revoked_at TIMESTAMPTZ,
	last_used_at TIMESTAMPTZ,
	last_used_ip TEXT NOT NULL DEFAULT '',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_api_keys_workspace ON api_keys (workspace_id, created_at DESC);

GRANT SELECT, INSERT, UPDATE ON api_keys TO qnetward_tenant;

ALTER TABLE api_keys ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON api_keys;
CREATE POLICY workspace_isolation ON api_keys
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
