-- Tier 2 deep scans: a workspace asks, with signed consent for an exact
-- scope and window; a Qnetward admin approves or rejects; only then does the
-- scan run. The consent text and its hash are kept as signed, never edited.
CREATE TABLE IF NOT EXISTS deep_scan_requests (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	domain TEXT NOT NULL,
	hosts TEXT[] NOT NULL,
	checks TEXT[] NOT NULL,
	window_start TIMESTAMPTZ NOT NULL,
	window_end TIMESTAMPTZ NOT NULL,
	consent_version TEXT NOT NULL,
	consent_text TEXT NOT NULL,
	consent_hash TEXT NOT NULL,
	consent_name TEXT NOT NULL,
	consent_ip TEXT NOT NULL DEFAULT '',
	consent_user_agent TEXT NOT NULL DEFAULT '',
	status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled', 'running', 'completed', 'failed', 'expired')),
	reviewer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	reviewer_email TEXT NOT NULL DEFAULT '',
	reviewed_at TIMESTAMPTZ,
	review_note TEXT NOT NULL DEFAULT '',
	scan_id BIGINT REFERENCES security_scans(id) ON DELETE SET NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CHECK (window_end > window_start)
);
CREATE INDEX IF NOT EXISTS idx_deep_scan_requests_workspace ON deep_scan_requests (workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_deep_scan_requests_status ON deep_scan_requests (status, window_start);

-- Workspaces see and cancel their own requests; reviews and runs go through
-- the login role.
GRANT SELECT, INSERT, UPDATE ON deep_scan_requests TO qnetward_tenant;

ALTER TABLE deep_scan_requests ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON deep_scan_requests;
CREATE POLICY workspace_isolation ON deep_scan_requests
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

ALTER TABLE security_scans DROP CONSTRAINT IF EXISTS security_scans_kind_check;
ALTER TABLE security_scans ADD CONSTRAINT security_scans_kind_check CHECK (kind IN ('passive', 'surface', 'deep'));
