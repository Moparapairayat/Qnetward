-- Passive security checks: each scan of a domain's public posture, kept so a
-- workspace can see its history and compare. The full report is JSON; the
-- grade and counts are columns so the list needs no JSON.
CREATE TABLE IF NOT EXISTS security_scans (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	kind TEXT NOT NULL DEFAULT 'passive' CHECK (kind IN ('passive')),
	domain TEXT NOT NULL,
	grade TEXT NOT NULL,
	score INTEGER NOT NULL,
	high INTEGER NOT NULL DEFAULT 0,
	medium INTEGER NOT NULL DEFAULT 0,
	low INTEGER NOT NULL DEFAULT 0,
	report JSONB NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_security_scans_workspace ON security_scans (workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_security_scans_domain ON security_scans (workspace_id, domain, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_security_scans_created ON security_scans (created_at);

GRANT SELECT, INSERT, DELETE ON security_scans TO qnetward_tenant;

ALTER TABLE security_scans ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON security_scans;
CREATE POLICY workspace_isolation ON security_scans
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
