-- Passkeys (WebAuthn). Each user gets a random handle that authenticators
-- store instead of anything identifying, as the WebAuthn spec recommends.
ALTER TABLE users ADD COLUMN IF NOT EXISTS webauthn_handle BYTEA UNIQUE;

CREATE TABLE IF NOT EXISTS webauthn_credentials (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	credential_id BYTEA NOT NULL UNIQUE,
	name TEXT NOT NULL,
	-- The library's credential record: public key, sign count, flags, transports.
	credential JSONB NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	last_used_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_webauthn_credentials_user ON webauthn_credentials (user_id);

-- Ceremony state between "begin" and "finish", single use and short-lived.
CREATE TABLE IF NOT EXISTS webauthn_challenges (
	token_hash TEXT PRIMARY KEY,
	user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
	kind TEXT NOT NULL,
	session JSONB NOT NULL,
	expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_webauthn_challenges_expires ON webauthn_challenges (expires_at);
