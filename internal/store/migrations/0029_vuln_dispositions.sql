-- What a workspace decided about a vulnerability on a host: an accepted
-- risk, or a false positive (such as a distribution that patched without
-- changing the version). Decided vulnerabilities stay listed but move out
-- of the way, with who decided and why.
CREATE TABLE IF NOT EXISTS vuln_dispositions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	host TEXT NOT NULL,
	cve TEXT NOT NULL,
	status TEXT NOT NULL CHECK (status IN ('accepted', 'false_positive')),
	reason TEXT NOT NULL DEFAULT '',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_vuln_dispositions_key ON vuln_dispositions (workspace_id, host, cve);

GRANT SELECT, INSERT, UPDATE, DELETE ON vuln_dispositions TO qnetward_tenant;

ALTER TABLE vuln_dispositions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON vuln_dispositions;
CREATE POLICY workspace_isolation ON vuln_dispositions
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
