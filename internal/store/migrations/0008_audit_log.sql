-- Audit log: an append-only record of who did what, and when.
--
-- Workspace events (members, monitors, alert rules, scans, exports) carry the
-- workspace and are readable by that workspace through row-level security.
-- Account events (sign-ins, password and session changes) have no workspace
-- and are shown only to the user they belong to.
CREATE TABLE IF NOT EXISTS audit_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	workspace_id BIGINT REFERENCES workspaces(id) ON DELETE CASCADE,
	-- No foreign key: the record must outlive the account that made it.
	actor_user_id BIGINT,
	actor_email TEXT NOT NULL DEFAULT '',
	action TEXT NOT NULL,
	target_type TEXT NOT NULL DEFAULT '',
	target_id TEXT NOT NULL DEFAULT '',
	target_label TEXT NOT NULL DEFAULT '',
	ip_address TEXT NOT NULL DEFAULT '',
	user_agent TEXT NOT NULL DEFAULT '',
	metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_audit_events_workspace ON audit_events (workspace_id, id DESC) WHERE workspace_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_audit_events_account ON audit_events (actor_user_id, id DESC) WHERE workspace_id IS NULL;
CREATE INDEX IF NOT EXISTS idx_audit_events_occurred_at ON audit_events (occurred_at);

-- Rows are never changed. Deletes stay possible for the login role only, for
-- retention and for removing a deleted workspace's data.
CREATE OR REPLACE FUNCTION audit_events_append_only() RETURNS trigger AS $$
BEGIN
	RAISE EXCEPTION 'audit events are append-only';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS audit_events_no_update ON audit_events;
CREATE TRIGGER audit_events_no_update BEFORE UPDATE ON audit_events
	FOR EACH ROW EXECUTE FUNCTION audit_events_append_only();

GRANT SELECT, INSERT ON audit_events TO qnetward_tenant;

ALTER TABLE audit_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON audit_events;
CREATE POLICY workspace_isolation ON audit_events
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
