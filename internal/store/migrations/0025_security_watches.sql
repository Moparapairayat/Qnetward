-- Watched domains: a passive check that re-runs on a schedule and alerts when
-- the grade drops or a new high-severity issue appears.
CREATE TABLE IF NOT EXISTS security_watches (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	domain TEXT NOT NULL,
	interval_hours INTEGER NOT NULL DEFAULT 24 CHECK (interval_hours IN (6, 24, 168)),
	notify_email TEXT NOT NULL DEFAULT '',
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	last_scan_id BIGINT REFERENCES security_scans(id) ON DELETE SET NULL,
	last_grade TEXT NOT NULL DEFAULT '',
	last_score INTEGER,
	last_checked_at TIMESTAMPTZ,
	last_error TEXT NOT NULL DEFAULT '',
	next_run_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_security_watches_domain ON security_watches (workspace_id, domain);
CREATE INDEX IF NOT EXISTS idx_security_watches_due ON security_watches (next_run_at) WHERE enabled;

GRANT SELECT, INSERT, UPDATE, DELETE ON security_watches TO qnetward_tenant;

ALTER TABLE security_watches ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON security_watches;
CREATE POLICY workspace_isolation ON security_watches
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

-- Channels that hear about certificates also hear about security checks.
UPDATE notification_channels
SET events = array_append(events, 'security')
WHERE 'certificates' = ANY(events) AND NOT ('security' = ANY(events));
