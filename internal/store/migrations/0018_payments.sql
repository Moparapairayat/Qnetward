-- One-time payments for a paid plan. UddoktaPay (bKash, Nagad, Rocket, cards)
-- has no subscriptions, so a payment buys a period: plan_expires_at moves
-- forward, and the workspace returns to Free when it passes. Plans an admin
-- sets by hand have no expiry.
ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS plan_expires_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS payments (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	provider TEXT NOT NULL DEFAULT 'uddoktapay',
	plan TEXT NOT NULL,
	months INTEGER NOT NULL CHECK (months > 0),
	amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
	currency TEXT NOT NULL DEFAULT 'BDT',
	status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed')),
	invoice_id TEXT UNIQUE,
	transaction_id TEXT NOT NULL DEFAULT '',
	payment_method TEXT NOT NULL DEFAULT '',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	paid_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_payments_workspace ON payments (workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_workspaces_plan_expiry ON workspaces (plan_expires_at) WHERE plan_expires_at IS NOT NULL;
