-- Live events: an append-only log per workspace that consoles stream and can
-- resume from. Each row gets a global, increasing id; a console that drops its
-- connection reconnects with the last id it saw and receives what it missed.
-- Rows are kept for a day; anything older means "refetch everything".
CREATE TABLE IF NOT EXISTS workspace_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	type TEXT NOT NULL,
	payload JSONB NOT NULL DEFAULT '{}'::jsonb,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_workspace_events_ws ON workspace_events (workspace_id, id);
CREATE INDEX IF NOT EXISTS idx_workspace_events_created ON workspace_events (created_at);

GRANT SELECT ON workspace_events TO qnetward_tenant;

ALTER TABLE workspace_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON workspace_events;
CREATE POLICY workspace_isolation ON workspace_events
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

-- Every new event is announced on one channel, so each API instance can push
-- it to the consoles connected to it. NOTIFY payloads are capped near 8000
-- bytes: a large event is announced by id alone and read back from the table.
CREATE OR REPLACE FUNCTION notify_workspace_event() RETURNS trigger AS $$
DECLARE
	msg TEXT;
BEGIN
	msg := json_build_object('id', NEW.id, 'w', NEW.workspace_id, 't', NEW.type, 'p', NEW.payload, 'at', NEW.created_at)::text;
	IF octet_length(msg) > 7500 THEN
		msg := json_build_object('id', NEW.id, 'w', NEW.workspace_id, 't', NEW.type, 'big', true, 'at', NEW.created_at)::text;
	END IF;
	PERFORM pg_notify('qnetward_events', msg);
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS workspace_events_notify ON workspace_events;
CREATE TRIGGER workspace_events_notify AFTER INSERT ON workspace_events
	FOR EACH ROW EXECUTE FUNCTION notify_workspace_event();
