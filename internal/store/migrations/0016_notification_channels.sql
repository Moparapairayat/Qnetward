-- Where a workspace's alerts go besides email: Slack, Discord, Telegram, or a
-- signed webhook. The destination (webhook URL, bot token, signing secret) is
-- sealed with the server's encryption key; `target` is a masked hint for the UI.
CREATE TABLE IF NOT EXISTS notification_channels (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
	kind TEXT NOT NULL CHECK (kind IN ('slack', 'discord', 'telegram', 'webhook')),
	name TEXT NOT NULL,
	target TEXT NOT NULL DEFAULT '',
	config_enc TEXT NOT NULL,
	-- Which alerts it receives: monitors, certificates, alert_rules.
	events TEXT[] NOT NULL,
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	last_sent_at TIMESTAMPTZ,
	last_error TEXT NOT NULL DEFAULT '',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_notification_channels_workspace ON notification_channels (workspace_id, created_at);

GRANT SELECT, INSERT, UPDATE, DELETE ON notification_channels TO qnetward_tenant;

ALTER TABLE notification_channels ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON notification_channels;
CREATE POLICY workspace_isolation ON notification_channels
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
